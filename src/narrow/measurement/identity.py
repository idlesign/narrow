"""Bounded identities of the actual controller and caller-selected payload files."""

import hashlib
import os
import platform
import stat
import sys
import sysconfig
from collections.abc import Mapping
from pathlib import Path

MAX_ARTIFACTS = 4096
MAX_ARTIFACT_BYTES = 256 * 1024**2
MAX_PAYLOAD_ENTRIES = 8192

def _validate_name(name: str) -> None:

    if (
        not isinstance(name, str) or not name.strip() or len(name) > 512 or "\\" in name
        or any(part in ("", ".", "..") for part in name.split("/"))
        or any(ord(character) < 32 or ord(character) == 127 or 0xD800 <= ord(character) <= 0xDFFF for character in name)
    ):
        raise ValueError("Artifact names must be relative paths without empty or parent components")

def _hash_file(path: Path, *, remaining: int) -> tuple[str, int]:
    observed = path.lstat()

    if not stat.S_ISREG(observed.st_mode):
        raise ValueError("Artifacts must be regular files, not symlinks or special files")

    if observed.st_size > remaining:
        raise ValueError("Artifact payload exceeds its size bound")

    descriptor = os.open(path, os.O_RDONLY | os.O_NONBLOCK | os.O_NOFOLLOW)

    with os.fdopen(descriptor, "rb") as stream:
        opened = os.fstat(stream.fileno())

        if not stat.S_ISREG(opened.st_mode) or (opened.st_dev, opened.st_ino) != (observed.st_dev, observed.st_ino):
            raise ValueError("Artifact changed while being opened")

        digest = hashlib.sha256()
        size = 0

        while chunk := stream.read(min(64 * 1024, remaining - size + 1)):
            size += len(chunk)

            if size > remaining:
                raise ValueError("Artifact payload exceeds its size bound")

            digest.update(chunk)

        final = os.fstat(stream.fileno())

        if size != observed.st_size or any(
            getattr(final, name) != getattr(observed, name)
            for name in ("st_dev", "st_ino", "st_size", "st_mtime_ns", "st_ctime_ns")
        ):
            raise ValueError("Artifact changed while being hashed")

    return digest.hexdigest(), size

def hash_artifacts(files: Mapping[str, Path]) -> dict[str, str]:
    """Hash named regular files without persisting their locations or copying contents."""

    if not isinstance(files, Mapping) or not 1 <= len(files) <= MAX_ARTIFACTS:
        raise ValueError(f"Artifact payload must contain 1..{MAX_ARTIFACTS} named files")

    for name, path in files.items():
        _validate_name(name)

        if not isinstance(path, Path):
            raise ValueError("Artifact paths must be pathlib.Path objects")

    result = {}
    total = 0

    for name, path in sorted(files.items()):
        result[name], size = _hash_file(path, remaining=MAX_ARTIFACT_BYTES - total)
        total += size

    return result

def _raise_walk_error(error: OSError) -> None:
    raise error

def hash_payload(root: Path, *, prefix: str) -> dict[str, str]:
    """Hash a bounded package tree, including resources but not generated bytecode."""
    _validate_name(prefix)

    if not isinstance(root, Path) or root.is_symlink() or not root.is_dir():
        raise ValueError("Payload root must be a real directory, not a symlink")

    files = {}
    entries = 0

    for directory, directories, filenames in os.walk(root, onerror=_raise_walk_error, followlinks=False):
        current = Path(directory)
        entries += len(directories) + len(filenames)

        if entries > MAX_PAYLOAD_ENTRIES:
            raise ValueError("Package payload exceeds its entry count bound")

        for name in (*directories, *filenames):
            path = current / name
            mode = path.lstat().st_mode

            if not stat.S_ISREG(mode) and not stat.S_ISDIR(mode):
                raise ValueError("Payload must not contain symlinks or special files")

            if stat.S_ISDIR(mode) or path.suffix in (".pyc", ".pyo"):
                continue

            files[f"{prefix}/{path.relative_to(root).as_posix()}"] = path

            if len(files) > MAX_ARTIFACTS:
                raise ValueError("Package payload exceeds its file count bound")

        directories[:] = [name for name in directories if name != "__pycache__"]

    return hash_artifacts(files)

def collect_controller_identity() -> dict:
    """Read narrow's current bytes and the running Python executable explicitly."""

    if not sys.executable:
        raise ValueError("Controller Python executable is unavailable")

    executable = Path(sys.executable).resolve()
    return {
        "narrow": {"payload_sha256": hash_payload(Path(__file__).parents[1], prefix="narrow")},
        "python": {
            "version": platform.python_version(), "implementation": sys.implementation.name,
            "abi": sysconfig.get_config_var("SOABI"),
            "gil_enabled": not bool(sysconfig.get_config_var("Py_GIL_DISABLED")),
            "sha256": hash_artifacts({"python": executable})["python"],
        },
    }
